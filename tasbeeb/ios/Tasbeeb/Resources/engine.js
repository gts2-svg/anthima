function ctx(){
  const pFem = S.f.pG==='أنثى'||S.f.pG==='جهة', dFem = S.f.dG==='أنثى'||S.f.dG==='جهة';
  const c = {f:S.f, ev:S.ev, text:S.text, pos:S.f.pos, type:T[S.type]};
  c.P = pFem?'المدعية':'المدعي';
  c.D = dFem?'المدعى عليها':'المدعى عليه';
  c.g = (m,fm)=>dFem?fm:m;          // تصريف بحسب المدعى عليه
  c.gp = (m,fm)=>pFem?fm:m;         // تصريف بحسب المدعي
  c.h = dFem?'ها':'ه';
  c.pp = pFem?'ها':'ه';   // ضمير المدعي
  c.pl = pFem?'لها':'له';
  c.attended = ATTENDED.includes(S.f.pos);
  c.amt = parseFloat(String(S.f.amount||'').replace(/[,٬]/g,''))||0;
  return c;
}
