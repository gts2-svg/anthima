// مطابقة ردّ مكتوب لخيار: «بيع» ← «عقد بيع»، «حضر وأقر» ← iqrar؛ وإلا null
function matchChoice(fd, v){
  const opts = fd.options || [], labs = opts.map(o => fd.labels ? fd.labels[o] : o);
  const n = s => String(s||'').replace(/[أإآ]/g,'ا').replace(/ى/g,'ي').replace(/ة/g,'ه').replace(/[ًٌٍَُِّْـ]/g,'').replace(/\s+/g,' ').trim();
  const nv = n(v); if(!nv) return '';
  let i = opts.findIndex((o,j) => n(o)===nv || n(labs[j])===nv); if(i>=0) return opts[i];
  if(nv.length>=2){ const h = opts.filter((o,j) => n(o).includes(nv) || n(labs[j]).includes(nv)); if(h.length===1) return h[0]; }
  const h2 = opts.filter((o,j) => (n(labs[j]).length>=3 && nv.includes(n(labs[j]))) || (n(o).length>=3 && nv.includes(n(o)))); if(h2.length===1) return h2[0];
  return null;
}
