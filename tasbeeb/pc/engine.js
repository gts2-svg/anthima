  if(S.type==='traffic'){ fillFromDoc('reportNo', firstItem('najm','reportNo'), 'رقم تقرير الحادث'); const rd=firstItem('najm','date'); if(rd && !S.f.reportDate && !attDry){ S.f.reportDate=hdate(rd); S.st.reportDate='unc'; } }
  if(S.type==='traffic'){ const r = firstItem('najm','ratios'); const ns=(r.match(/[0-9]+/g)||[]).map(Number); if(ns.length && !S.f.ratio && !attDry){ S.f.ratio=String(Math.max(...ns)); S.st.ratio='unc'; } }
