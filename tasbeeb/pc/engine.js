const STOP2 = /\s(?:و|ف)?(?:أطلب|اطلب|نطلب|يطلب|تطلب)(?:\s|$|،)|\s(?:على|إلى|الى|من)?\s*(?:ال|لل)مدع[ىي](?:\s|$|،)|\s(?:ذات\s+)?(?:ال)?لوحة(?:\s|$|،)/;
function nounPhrase(text, nouns){
  const re = new RegExp('(^|[\\s،.(])(لل|ال|ل|ب)?('+nouns+')([^،.؛\\n]{0,60})');
  const m = text.match(re); if(!m) return '';
  let s = ('ال'+m[3]+m[4]).replace(/^الال/,'ال');
  const k = s.search(STOP); if(k>0) s = s.slice(0,k);
  const k2 = s.search(STOP2); if(k2>0) s = s.slice(0,k2);
  s = s.split(/\s+/).slice(0,7).join(' ').replace(/\s+(رقم|في|بحي|حي|ب|و)$/,'').trim();
  return s;
}
